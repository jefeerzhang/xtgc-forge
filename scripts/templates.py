# init 替换的参数化 token（在上方模板中真实存在;集合即契约）。
# 这四个在 init 时被替换,其余 token 留给用户填写、填前全部是拦截对象。
FILL_TOKENS = ("<YYYY-MM-DD>", "<研究主题>", "<推断性|描述性|质性>", "<zh-CN|en-US>")

# init 产物签名行:识别「模板尚未填写」用的模板契约模式（非用户占位符）。
GENERATOR_SIGNATURE_PATTERN = r"由 `?init_project\.py`? 自动生成"

_TOKEN_RE = re.compile(r"<[^<>\n]+>")


def template_placeholders() -> list[str]:
    """列出模板正文中出现的全部 <...> 占位 token（去重、保序）。

    HTML 注释行（<!-- ... -->）是编辑提示,不是占位符,不参与派生。
    """
    seen: set[str] = set()
    out: list[str] = []
    for content in TEMPLATES.values():
        for line in content.splitlines():
            if line.strip().startswith("<!--"):
                continue
            for tok in _TOKEN_RE.findall(line):
                if tok not in seen:
                    seen.add(tok)
                    out.append(tok)
    return out


def placeholder_patterns() -> list[str]:
    """从模板文本派生的模板空壳拦截正则族。

    每个 token → 精确匹配 + 空白放宽（token 内空白位容忍任意空白）,
    覆盖 <来源 Gap 编号>/<这个题揭示了什么?...> 等模板家族;外加产物签名行。
    """
    out = []
    for tok in template_placeholders():
        parts = [re.escape(p) for p in tok.split()]
        out.append(r"\s+".join(parts) if len(parts) > 1 else parts[0])
    out.append(GENERATOR_SIGNATURE_PATTERN)
    return out
